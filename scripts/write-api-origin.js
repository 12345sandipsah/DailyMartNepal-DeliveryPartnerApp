const fs = require('node:fs');
const path = require('node:path');

const configuredUrl = process.env.DAILYMART_API_BASE_URL?.trim();

if (!configuredUrl) {
  if (process.env.CI === 'true') {
    throw new Error('Set DAILYMART_API_BASE_URL for the cloud test build.');
  }
  process.exit(0);
}

const parsedUrl = new URL(configuredUrl);
if (parsedUrl.protocol !== 'https:') {
  throw new Error('DAILYMART_API_BASE_URL must use HTTPS for cloud builds.');
}

const apiOrigin = `${parsedUrl.origin}${parsedUrl.pathname}`
  .replace(/\/+$/, '')
  .replace(/\/api$/i, '');
const configPath = path.join(__dirname, '..', 'src', 'shared', 'config', 'apiOrigin.ts');
fs.writeFileSync(
  configPath,
  `// Generated by the Android preview build workflow.\nexport const API_ORIGIN = ${JSON.stringify(apiOrigin)};\n`,
);
